-- Idempotent setup for the public guestbook and casual game leaderboard.

create table if not exists public.guestbook_entries (
  id bigint generated by default as identity primary key,
  name varchar(18) not null,
  message varchar(180) not null,
  created_at timestamptz not null default now(),
  constraint guestbook_name_not_blank check (char_length(btrim(name)) between 1 and 18),
  constraint guestbook_message_not_blank check (char_length(btrim(message)) between 1 and 180)
);

create table if not exists public.game_scores (
  id bigint generated by default as identity primary key,
  game varchar(20) not null default 'tetris',
  player_name varchar(10) not null,
  score integer not null,
  lines integer not null,
  created_at timestamptz not null default now(),
  constraint game_score_name_not_blank check (char_length(btrim(player_name)) between 1 and 10),
  constraint game_score_type check (game in ('tetris', 'suika')),
  constraint game_score_range check (score between 0 and 999999999),
  constraint game_lines_range check (lines between 0 and 999999)
);

alter table public.game_scores
  add column if not exists game varchar(20) not null default 'tetris';

do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conname = 'game_score_type'
      and conrelid = 'public.game_scores'::regclass
  ) then
    alter table public.game_scores
      add constraint game_score_type check (game in ('tetris', 'suika'));
  end if;
end
$$;

create index if not exists game_scores_ranking_idx
  on public.game_scores (score desc, lines desc, created_at asc);
create index if not exists game_scores_game_ranking_idx
  on public.game_scores (game, score desc, lines desc, created_at asc);

alter table public.guestbook_entries enable row level security;
alter table public.game_scores enable row level security;

revoke all on table public.guestbook_entries from anon, authenticated;
revoke all on table public.game_scores from anon, authenticated;

grant select on table public.guestbook_entries to anon, authenticated;
grant insert (name, message) on table public.guestbook_entries to anon, authenticated;
grant select on table public.game_scores to anon, authenticated;
grant insert (game, player_name, score, lines) on table public.game_scores to anon, authenticated;
grant usage, select on sequence public.guestbook_entries_id_seq to anon, authenticated;
grant usage, select on sequence public.game_scores_id_seq to anon, authenticated;

drop policy if exists "Public can read guestbook" on public.guestbook_entries;
create policy "Public can read guestbook"
  on public.guestbook_entries for select
  to anon, authenticated
  using (true);

drop policy if exists "Public can add guestbook entries" on public.guestbook_entries;
create policy "Public can add guestbook entries"
  on public.guestbook_entries for insert
  to anon, authenticated
  with check (
    char_length(btrim(name)) between 1 and 18
    and char_length(btrim(message)) between 1 and 180
  );

drop policy if exists "Public can read game scores" on public.game_scores;
create policy "Public can read game scores"
  on public.game_scores for select
  to anon, authenticated
  using (true);

drop policy if exists "Public can add game scores" on public.game_scores;
create policy "Public can add game scores"
  on public.game_scores for insert
  to anon, authenticated
  with check (
    char_length(btrim(player_name)) between 1 and 10
    and game in ('tetris', 'suika')
    and score between 0 and 999999999
    and lines between 0 and 999999
  );
